"""
Build the photo gallery: converts source JPEGs into WebP (1600 px for the
lightbox, 640 px thumbnails) under public/gallery and writes src/gallery.ts.

Usage: python3 scripts/gallery.py <manifest.json>

The manifest is a list of {"file": "/abs/path.jpg", "name": "shoot-0047",
"alt": "...", "caption": "...", "set": "Shooting 2026"}; order is kept.
"""
import json
import os
import sys

from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "gallery")
os.makedirs(OUT, exist_ok=True)

manifest = json.load(open(sys.argv[1]))
entries = []
for item in manifest:
    im = ImageOps.exif_transpose(Image.open(item["file"])).convert("RGB")
    w, h = im.size
    full = im.copy()
    full.thumbnail((1600, 1600), Image.LANCZOS)
    full.save(os.path.join(OUT, f'{item["name"]}.webp'), "WEBP", quality=82, method=6)
    thumb = im.copy()
    thumb.thumbnail((640, 640), Image.LANCZOS)
    thumb.save(os.path.join(OUT, f'{item["name"]}-s.webp'), "WEBP", quality=78, method=6)
    entries.append(
        {
            "src": f'/gallery/{item["name"]}.webp',
            "thumb": f'/gallery/{item["name"]}-s.webp',
            "w": full.size[0],
            "h": full.size[1],
            "alt": item["alt"],
            "caption": item["caption"],
            "set": item["set"],
        }
    )
    print(item["name"], w, h, "->", full.size)

ts = (
    "export type Photo = {\n"
    "  /** full-size (lightbox) image */\n  src: string;\n"
    "  /** grid thumbnail */\n  thumb: string;\n"
    "  w: number;\n  h: number;\n  alt: string;\n  caption: string;\n  set: string;\n};\n\n"
    "/** Generated by scripts/gallery.py; edit the manifest, not this file. */\n"
    "export const gallery: Photo[] = " + json.dumps(entries, ensure_ascii=False, indent=2) + ";\n"
)
open(os.path.join(ROOT, "src", "gallery.ts"), "w").write(ts)
print("wrote", len(entries), "photos")
